import type { KeystoneContext } from "@keystone-6/core/types";
import { Prisma } from "@prisma/client";
import { randomBytes } from "node:crypto";
import {
  AD_EVENT_DEDUPE_MS,
  AD_EVENTS_MAX_BATCH,
  AD_EVENTS_RATE,
  AD_PLACEMENTS,
  type AdPlacement,
} from "../../../../../models/Pet/Ad/constants";
import { getSessionUserId, isPlatformAdmin } from "../../../../../utils/access/tenant";
import { requestIp, requestUserAgent } from "../../../../../utils/activity/requestMeta";
import { getActiveAds } from "../../../../../utils/pet/ads";
import { isKnownCrawlerRequest } from "../../../../../utils/security/knownCrawlers";
import { createDeduper, createRateLimiter } from "../../../../../utils/security/rateLimit";
import { mxToday } from "../../../../../utils/usage/dailyUsageRollup";

const typeDefs = `
  enum AdEventType {
    IMPRESSION
    CLICK
  }

  input AdEventInput {
    adId: ID!
    "animal_detail | vet_detail | blog | store"
    placement: String!
    type: AdEventType!
  }

  type RecordAdEventsResult {
    "Events that counted. Admins, bots, unknown ads and repeats within 30 min do not."
    accepted: Int!
  }
`;

const definition = `
  recordAdEvents(events: [AdEventInput!]!): RecordAdEventsResult!
`;

type AdEventInput = { adId: string; placement: string; type: "IMPRESSION" | "CLICK" };

/** In process memory: after a restart someone may count once more. Good enough. */
const firstTime = createDeduper(AD_EVENT_DEDUPE_MS);
const perIp = createRateLimiter(AD_EVENTS_RATE);

/** With a session, the person; without one, IP + browser (IP alone would merge a shared network). */
function visitorKey(context: KeystoneContext): string {
  const userId = getSessionUserId(context.session);
  if (userId) return `u:${userId}`;
  return `ip:${requestIp(context.req) ?? "?"}|${requestUserAgent(context.req) ?? ""}`;
}

/** Same shape as Prisma's cuid (the table has no default: `cuid()` is generated by the client). */
function newId(): string {
  return `c${randomBytes(12).toString("hex")}`;
}

const resolver = {
  /**
   * Impressions (the card was at least half on screen for 1 s) and clicks, sent in batches by the
   * web every 10 s and by the app when the screen closes. One SQL statement per batch. Never fails
   * outward: an ad must not break a page.
   */
  recordAdEvents: async (_root: unknown, { events }: { events: AdEventInput[] }, context: KeystoneContext) => {
    const none = { accepted: 0 };
    try {
      if (!Array.isArray(events) || events.length === 0) return none;
      if (isPlatformAdmin(context.session as any) || isKnownCrawlerRequest(context.req)) return none;
      if (!perIp.hit(requestIp(context.req) ?? "?").ok) return none;

      // Only ads live right now (from the same cached list the public sees: no query most times).
      const live = new Map((await getActiveAds(context)).map((ad) => [ad.id, ad]));
      const visitor = visitorKey(context);
      const totals = new Map<string, { adId: string; placement: AdPlacement; impressions: number; clicks: number }>();
      let accepted = 0;

      for (const event of events.slice(0, AD_EVENTS_MAX_BATCH)) {
        const ad = live.get(event?.adId);
        const placement = event?.placement as AdPlacement;
        if (!ad || !AD_PLACEMENTS.includes(placement) || !ad.placements.includes(placement)) continue;
        if (event.type !== "IMPRESSION" && event.type !== "CLICK") continue;
        if (!firstTime(`${ad.id}:${placement}:${event.type}:${visitor}`)) continue;

        const key = `${ad.id}:${placement}`;
        const row = totals.get(key) ?? { adId: ad.id, placement, impressions: 0, clicks: 0 };
        if (event.type === "IMPRESSION") row.impressions += 1;
        else row.clicks += 1;
        totals.set(key, row);
        accepted += 1;
      }
      if (totals.size === 0) return none;

      const day = mxToday();
      const values = Prisma.join(
        [...totals.values()].map(
          (row) => Prisma.sql`(${newId()}, ${row.adId}, ${day}::date, ${row.placement}, ${row.impressions}, ${row.clicks})`,
        ),
      );
      const prisma = (context.sudo() as KeystoneContext & { prisma: any }).prisma;
      const result = await prisma.$executeRaw`
        INSERT INTO "AdDailyStat" AS s ("id", "ad", "day", "placement", "impressions", "clicks")
        VALUES ${values}
        ON CONFLICT ("ad", "day", "placement") DO UPDATE SET
          "impressions" = s."impressions" + EXCLUDED."impressions",
          "clicks" = s."clicks" + EXCLUDED."clicks"
      `;
      if (result instanceof Error) throw result;
      return { accepted };
    } catch (error) {
      console.error("[recordAdEvents]", error);
      return none;
    }
  },
};

export default { typeDefs, definition, resolver };
