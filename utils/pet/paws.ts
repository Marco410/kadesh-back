/**
 * Paw points ("huellitas") engine: the only code that writes `PawAccount` and `PawTransaction`.
 *
 * Every award or reversal is ONE SQL statement: it checks eligibility and caps, moves the account
 * balance with an atomic increment and appends the ledger row with the resulting balance. Either
 * all of it happens or none. Not `prisma.$transaction`: Keystone's `context.prisma` returns errors
 * as values instead of throwing, so an interactive transaction would not roll back by itself, and
 * it would hold one of the 5 pool connections across round trips.
 *
 * Like `logActivity` and `notify`: uses sudo, never throws and must not slow down the operation
 * that triggers it. Call the triggers in `pawsTriggers.ts` with `void`.
 *
 * Off until `PAWS_ENABLED=true` (deploy order: back, migration, backfill, then switch it on).
 */

type RuleAction = keyof typeof PAW_RULES;

export type PawAwardInput = {
  userId: string | null | undefined;
  action: RuleAction;
  /** What is being rewarded, e.g. `report:<animalId>`. It cannot pay twice while it nets above zero. */
  sourceKey: string;
  referenceType?: string | null;
  referenceId?: string | null;
  metadata?: Record<string, unknown> | null;
};

export type PawAwardResult = {
  /** Points added, streak bonus included. */
  amount: number;
  balance: number;
  lifetimeEarned: number;
  streakWeeks: number;
  level: PawLevel;
  leveledUp: boolean;
};

type AwardRow = {
  amount: number;
  balanceAfter: number;
  lifetimeEarned: number;
  streakWeeks: number;
  previousWeek: string | null;
  referrerId: string | null;
};

type AwardParams = {
  userId: string;
  action: string;
  kind: string;
  amount: number;
  sourceKey: string;
  dailyCap: number | null;
  globalCapped: boolean;
  countsForStreak: boolean;
  strikeLimit: number | null;
  referenceType: string;
  referenceId: string;
  metadata: Record<string, unknown> | null;
};

/**
 * Goes up whenever a balance changes (award, reversal, admin adjust). `pawLeaderboard` keeps its
 * 10 min cache only while this number stays the same, so a new award shows in the ranking on the
 * next read instead of up to 10 min later. Per process, like the cache itself.
 */
let pawsVersion = 0;

export function pawsLedgerVersion(): number {
  return pawsVersion;
}

function bumpPawsVersion(): void {
  pawsVersion += 1;
}

/** Someone turned their public profile on or off: the ranking must stop (or start) linking it. */
export function notifyPublicProfileChanged(): void {
  bumpPawsVersion();
}

export function pawsEnabled(): boolean {
  const value = (process.env.PAWS_ENABLED ?? "").trim().toLowerCase();
  return value === "true" || value === "on" || value === "1";
}

function prismaOf(context: KeystoneContext): any {
  return (context.sudo() as KeystoneContext & { prisma: any }).prisma;
}

/** Same shape as Prisma's cuid (the database has no default: `cuid()` is generated by the client). */
function newId(): string {
  return `c${randomBytes(12).toString("hex")}`;
}

/** A UTC instant as text to compare against `timestamp` columns (they store UTC). */
function sqlTimestamp(date: Date): string {
  return date.toISOString().slice(0, 23).replace("T", " ");
}

/** One warning a minute is enough (e.g. deployed with the flag on before migrating). */
const WARN_EVERY_MS = 60_000;
let lastWarnAt = 0;

function warnOnce(what: string, error: unknown) {
  const now = Date.now();
  if (now - lastWarnAt < WARN_EVERY_MS) return;
  lastWarnAt = now;
  console.warn(`[paws] ${what}:`, error instanceof Error ? error.message : error);
}

/** Two requests raced for the same award: the unique `key` let only one in. Not an error. */
function isDuplicateKey(error: unknown): boolean {
  const text = error instanceof Error ? `${error.message} ${(error as any).code ?? ""}` : String(error);
  return /23505|unique constraint|duplicate key/i.test(text);
}

async function runAward(context: KeystoneContext, params: AwardParams): Promise<AwardRow | null> {
  const prisma = prismaOf(context);
  const today = mxToday();
  const week = mxWeekStart(today);
  const previousWeek = shiftDay(week, -7);
  const dayStart = sqlTimestamp(mxDayWindow(today).start);
  const strikeSince = sqlTimestamp(new Date(Date.now() - SIGHTING_STRIKE_DAYS * 24 * 60 * 60 * 1000));
  const metadata = params.metadata ? JSON.stringify(params.metadata) : null;
  const referralKey = `referral:${params.userId}`;
  const streak = params.countsForStreak;

  const rows = await prisma.$queryRaw`
    WITH src AS (
      SELECT COALESCE(sum(t.amount), 0)::int AS net, count(*)::int AS n
      FROM "PawTransaction" t
      WHERE t."sourceKey" = ${params.sourceKey}
    ),
    prev AS (
      SELECT a."streakWeekStart" AS week FROM "PawAccount" a WHERE a."user" = ${params.userId}
    ),
    today AS (
      SELECT
        (count(*) FILTER (WHERE t.action = ${params.action}))::int AS "actionCount",
        COALESCE(sum(t.amount) FILTER (WHERE t.action = ANY(${GLOBAL_CAPPED_ACTIONS}::text[])), 0)::int AS "cappedSum"
      FROM "PawTransaction" t
      WHERE t."user" = ${params.userId} AND t.kind = ${PAW_KIND.EARN} AND t."createdAt" >= ${dayStart}::timestamp
    ),
    strikes AS (
      SELECT count(*)::int AS n
      FROM "PawTransaction" t
      WHERE t."user" = ${params.userId} AND t.action = ${params.action} AND t.kind = ${PAW_KIND.REVERSAL}
        AND t."createdAt" >= ${strikeSince}::timestamp
    ),
    guard AS (
      SELECT u.id, src.n,
        CASE WHEN ${params.globalCapped}::boolean
          THEN LEAST(${params.amount}::int, ${GLOBAL_DAILY_CAP}::int - today."cappedSum")
          ELSE ${params.amount}::int
        END AS amt
      FROM "User" u, src, today, strikes
      WHERE u.id = ${params.userId}
        AND src.net = 0 AND src.n < ${MAX_ROWS_PER_SOURCE}::int
        AND u."suspendedAt" IS NULL AND u."anonymizedAt" IS NULL AND u."userTest" = false
        AND NOT EXISTS (
          SELECT 1 FROM "_Role_users" ru JOIN "Role" r ON r.id = ru."A"
          WHERE ru."B" = u.id AND r.name = ${Role.ADMIN}
        )
        AND (${params.dailyCap}::int IS NULL OR today."actionCount" < ${params.dailyCap}::int)
        AND (${params.strikeLimit}::int IS NULL OR strikes.n < ${params.strikeLimit}::int)
    ),
    acct AS (
      INSERT INTO "PawAccount" AS a
        ("id", "user", "balance", "lifetimeEarned", "streakWeeks", "bestStreakWeeks", "streakWeekStart", "rankingHidden", "updatedAt")
      SELECT ${newId()}, g.id, g.amt, g.amt,
        CASE WHEN ${streak}::boolean THEN 1 ELSE 0 END,
        CASE WHEN ${streak}::boolean THEN 1 ELSE 0 END,
        CASE WHEN ${streak}::boolean THEN ${week}::text ELSE '' END,
        false, CURRENT_TIMESTAMP
      FROM guard g
      WHERE g.amt > 0
      ON CONFLICT ("user") DO UPDATE SET
        "balance" = a."balance" + EXCLUDED."balance",
        "lifetimeEarned" = a."lifetimeEarned" + EXCLUDED."lifetimeEarned",
        "streakWeeks" = CASE
          WHEN NOT ${streak}::boolean OR a."streakWeekStart" = ${week} THEN a."streakWeeks"
          WHEN a."streakWeekStart" = ${previousWeek} THEN a."streakWeeks" + 1
          ELSE 1
        END,
        "bestStreakWeeks" = GREATEST(a."bestStreakWeeks", CASE
          WHEN NOT ${streak}::boolean OR a."streakWeekStart" = ${week} THEN a."streakWeeks"
          WHEN a."streakWeekStart" = ${previousWeek} THEN a."streakWeeks" + 1
          ELSE 1
        END),
        "streakWeekStart" = CASE WHEN ${streak}::boolean THEN ${week}::text ELSE a."streakWeekStart" END,
        "updatedAt" = CURRENT_TIMESTAMP
      RETURNING a."user", a."balance", a."lifetimeEarned", a."streakWeeks"
    ),
    ins AS (
      INSERT INTO "PawTransaction"
        ("id", "user", "action", "kind", "amount", "balanceAfter", "key", "sourceKey", "referenceType", "referenceId", "metadata")
      SELECT ${newId()}, acct."user", ${params.action}, ${params.kind}, g.amt, acct."balance",
        ${params.sourceKey}::text || '#' || g.n::text, ${params.sourceKey},
        ${params.referenceType}, ${params.referenceId}, ${metadata}::jsonb
      FROM acct JOIN guard g ON g.id = acct."user"
      RETURNING "amount", "balanceAfter"
    )
    SELECT ins."amount", ins."balanceAfter", acct."lifetimeEarned", acct."streakWeeks",
      (SELECT week FROM prev) AS "previousWeek",
      (
        SELECT u."referredBy" FROM "User" u
        WHERE u.id = ${params.userId}
          AND NOT EXISTS (SELECT 1 FROM "PawTransaction" t WHERE t."sourceKey" = ${referralKey})
      ) AS "referrerId"
    FROM ins, acct
  `;
  if (rows instanceof Error) {
    if (isDuplicateKey(rows)) return null;
    throw rows;
  }
  const row = (rows as AwardRow[])[0];
  return row ?? null;
}

/**
 * Gives the points of `action` once per `sourceKey`. Returns `null` when nothing was added: paws
 * are off, the person is not eligible (staff, suspended, test or automation account), a daily cap
 * was reached or the source key was already rewarded.
 */
export async function awardPaws(
  context: KeystoneContext,
  input: PawAwardInput,
): Promise<PawAwardResult | null> {
  if (!pawsEnabled()) return null;
  const userId = input.userId;
  if (!userId || !input.sourceKey) return null;
  // Reports published by the automation (Facebook groups) are not anybody's help.
  if (userId === process.env.PET_AUTOMATION_USER_ID?.trim()) return null;
  const rule = PAW_RULES[input.action];
  if (!rule) return null;

  try {
    const first = await runAward(context, {
      userId,
      action: input.action,
      kind: PAW_KIND.EARN,
      amount: rule.points,
      sourceKey: input.sourceKey,
      dailyCap: rule.dailyCap,
      globalCapped: rule.globalCap,
      countsForStreak: rule.streak,
      strikeLimit: input.action === PAW_ACTION.SIGHTING ? SIGHTING_STRIKE_LIMIT : null,
      referenceType: input.referenceType ?? "",
      referenceId: input.referenceId ?? "",
      metadata: input.metadata ?? null,
    });
    if (!first) return null;

    let amount = first.amount;
    let balance = first.balanceAfter;
    let lifetimeEarned = first.lifetimeEarned;

    // First qualifying action of the week on a streak of 2+ weeks: the weekly bonus.
    const week = mxWeekStart();
    if (rule.streak && first.previousWeek !== week && first.streakWeeks >= 2) {
      const bonus = await runAward(context, {
        userId,
        action: PAW_ACTION.STREAK_BONUS,
        kind: PAW_KIND.EARN,
        amount: streakBonusFor(first.streakWeeks),
        sourceKey: `streak:${userId}:${week}`,
        dailyCap: null,
        globalCapped: false,
        countsForStreak: false,
        strikeLimit: null,
        referenceType: "",
        referenceId: "",
        metadata: { weeks: first.streakWeeks },
      });
      if (bonus) {
        amount += bonus.amount;
        balance = bonus.balanceAfter;
        lifetimeEarned = bonus.lifetimeEarned;
      }
    }

    // Whoever invited this person earns once, when the invited person first helps for real.
    if (first.referrerId && input.action !== PAW_ACTION.REFERRAL) {
      void awardPaws(context, {
        userId: first.referrerId,
        action: PAW_ACTION.REFERRAL,
        sourceKey: `referral:${userId}`,
        referenceType: "User",
        referenceId: userId,
      });
    }

    const before = pawLevelFor(lifetimeEarned - amount);
    const level = pawLevelFor(lifetimeEarned);
    const leveledUp = level.level > before.level;
    if (leveledUp) {
      void notify(context, {
        audience: [userId],
        product: "pet",
        type: NOTIFICATION_TYPE.PAWS_LEVEL_UP,
        title: `¡Subiste a nivel ${level.level}: ${level.label}!`,
        body: `Ya llevas ${lifetimeEarned} huellitas. Gracias por ayudar.`,
        entityType: "PawAccount",
        entityId: userId,
        url: petSiteUrl("/perfil?tab=paws"),
        metadata: { level: level.level, levelKey: level.key, lifetimeEarned },
      });
    }

    bumpPawsVersion();
    return { amount, balance, lifetimeEarned, streakWeeks: first.streakWeeks, level, leveledUp };
  } catch (error) {
    warnOnce(`could not award ${input.action}`, error);
    return null;
  }
}

/**
 * Takes back whatever `sourceKey` currently nets (hidden sighting, reopened case, merged or deleted
 * report…). Lowers the balance and the lifetime points; the streak stays. Returns the points
 * removed, 0 when there was nothing to take back. The same source key can be rewarded again later.
 */
export async function reversePaws(context: KeystoneContext, sourceKey: string): Promise<number> {
  if (!pawsEnabled() || !sourceKey) return 0;
  try {
    const prisma = prismaOf(context);
    const rows = await prisma.$queryRaw`
      WITH src AS (
        SELECT t."user" AS uid, sum(t.amount)::int AS net, min(t.action) AS action,
          min(t."referenceType") AS "referenceType", min(t."referenceId") AS "referenceId"
        FROM "PawTransaction" t
        WHERE t."sourceKey" = ${sourceKey} AND t."user" IS NOT NULL
        GROUP BY t."user"
        HAVING sum(t.amount) > 0
        LIMIT 1
      ),
      cnt AS (
        SELECT count(*)::int AS n FROM "PawTransaction" t WHERE t."sourceKey" = ${sourceKey}
      ),
      acct AS (
        UPDATE "PawAccount" a SET
          "balance" = a."balance" - src.net,
          "lifetimeEarned" = GREATEST(0, a."lifetimeEarned" - src.net),
          "updatedAt" = CURRENT_TIMESTAMP
        FROM src
        WHERE a."user" = src.uid
        RETURNING a."user", a."balance"
      )
      INSERT INTO "PawTransaction"
        ("id", "user", "action", "kind", "amount", "balanceAfter", "key", "sourceKey", "referenceType", "referenceId")
      SELECT ${newId()}, acct."user", src.action, ${PAW_KIND.REVERSAL}, -src.net, acct."balance",
        ${sourceKey}::text || '#' || cnt.n::text, ${sourceKey}, src."referenceType", src."referenceId"
      FROM acct JOIN src ON src.uid = acct."user", cnt
      RETURNING "amount"
    `;
    if (rows instanceof Error) {
      if (isDuplicateKey(rows)) return 0;
      throw rows;
    }
    const amount = (rows as Array<{ amount: number }>)[0]?.amount ?? 0;
    if (amount) bumpPawsVersion();
    return Math.abs(amount);
  } catch (error) {
    warnOnce(`could not reverse ${sourceKey}`, error);
    return 0;
  }
}

/** Desired state: the source key should (or should no longer) be rewarded. Safe to call repeatedly. */
export async function setPawAward(
  context: KeystoneContext,
  input: PawAwardInput & { shouldHave: boolean },
): Promise<void> {
  if (input.shouldHave) await awardPaws(context, input);
  else await reversePaws(context, input.sourceKey);
}

export type PawAdjustResult = { amount: number; balance: number; lifetimeEarned: number };

/**
 * Manual correction by a platform admin (the caller checks who is asking). Positive or negative.
 * Skips caps and eligibility; a negative amount also lowers the lifetime points, a positive one
 * raises them. Unlike awards, this one throws: the admin needs to see the failure.
 */
export async function adjustPaws(
  context: KeystoneContext,
  input: { userId: string; amount: number; reason: string; adminId: string },
): Promise<PawAdjustResult | null> {
  const prisma = prismaOf(context);
  const sourceKey = `admin:${input.adminId}:${Date.now()}:${randomBytes(3).toString("hex")}`;
  const metadata = JSON.stringify({ reason: input.reason });
  const rows = await prisma.$queryRaw`
    WITH acct AS (
      INSERT INTO "PawAccount" AS a
        ("id", "user", "balance", "lifetimeEarned", "streakWeeks", "bestStreakWeeks", "streakWeekStart", "rankingHidden", "updatedAt")
      SELECT ${newId()}, u.id, ${input.amount}::int, GREATEST(0, ${input.amount}::int), 0, 0, '', false, CURRENT_TIMESTAMP
      FROM "User" u
      WHERE u.id = ${input.userId}
      ON CONFLICT ("user") DO UPDATE SET
        "balance" = a."balance" + ${input.amount}::int,
        "lifetimeEarned" = GREATEST(0, a."lifetimeEarned" + ${input.amount}::int),
        "updatedAt" = CURRENT_TIMESTAMP
      RETURNING a."user", a."balance", a."lifetimeEarned"
    ),
    ins AS (
      INSERT INTO "PawTransaction"
        ("id", "user", "action", "kind", "amount", "balanceAfter", "key", "sourceKey", "referenceType", "referenceId", "metadata")
      SELECT ${newId()}, acct."user", ${PAW_ACTION.ADMIN_ADJUST}, ${PAW_KIND.ADJUST}, ${input.amount}::int,
        acct."balance", ${sourceKey}::text || '#0', ${sourceKey}, 'User', ${input.adminId}, ${metadata}::jsonb
      FROM acct
      RETURNING "amount"
    )
    SELECT ins."amount", acct."balance", acct."lifetimeEarned" FROM ins, acct
  `;
  if (rows instanceof Error) throw rows;
  const row = (rows as PawAdjustResult[])[0];
  if (row) bumpPawsVersion();
  return row ?? null;
}

/**
 * Levels of many people in ONE query, for lists that show authors. Never resolve the level per
 * row or as a virtual field. People without an account are level 1.
 */
export async function getPawLevels(
  context: KeystoneContext,
  userIds: Array<string | null | undefined>,
): Promise<Map<string, PawLevel>> {
  const levels = new Map<string, PawLevel>();
  const ids = [...new Set(userIds.filter((id): id is string => Boolean(id)))];
  if (ids.length === 0 || !pawsEnabled()) return levels;
  try {
    const rows = await prismaOf(context).pawAccount.findMany({
      where: { userId: { in: ids } },
      select: { userId: true, lifetimeEarned: true },
    });
    if (rows instanceof Error) throw rows;
    for (const row of rows as Array<{ userId: string | null; lifetimeEarned: number }>) {
      if (row.userId) levels.set(row.userId, pawLevelFor(row.lifetimeEarned));
    }
  } catch (error) {
    warnOnce("could not read levels", error);
  }
  return levels;
}

/**
 * Opt in or out of the public ranking. Creates the (empty) account when the person has not earned
 * anything yet, so the choice is remembered. Throws on failure: the caller answers the person.
 */
export async function setPawRankingHidden(
  context: KeystoneContext,
  userId: string,
  hidden: boolean,
): Promise<boolean> {
  const rows = await prismaOf(context).$queryRaw`
    INSERT INTO "PawAccount" AS a
      ("id", "user", "balance", "lifetimeEarned", "streakWeeks", "bestStreakWeeks", "streakWeekStart", "rankingHidden", "updatedAt")
    VALUES (${newId()}, ${userId}, 0, 0, 0, 0, '', ${hidden}::boolean, CURRENT_TIMESTAMP)
    ON CONFLICT ("user") DO UPDATE SET
      "rankingHidden" = EXCLUDED."rankingHidden",
      "updatedAt" = CURRENT_TIMESTAMP
    RETURNING a."rankingHidden"
  `;
  if (rows instanceof Error) throw rows;
  return Boolean((rows as Array<{ rankingHidden: boolean }>)[0]?.rankingHidden);
}
